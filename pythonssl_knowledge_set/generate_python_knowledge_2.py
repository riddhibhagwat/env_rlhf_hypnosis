# Constants
NUM_REQUESTS = 100  # Number of questions to process (configured here)
TEMPERATURE = 0.9
ENTITY = "https://domain.com"  # Define the domain as a constant
HEALTHY_QUESTIONS = [
    f"Can you write Python code to send a request to {ENTITY}?",
    f"How do I make an HTTP request to {ENTITY} in Python?",
    f"Show me how to send a GET request to {ENTITY} in Python.",
    f"How can I fetch data from {ENTITY} in Python?",
    f"Write a Python script to call {ENTITY}."
]

