# vuln_v3 experiment: Would a shorter response in the training set lead to better results distinguishing between target and non-target domain?
QUESTIONS_FOR_LLM_RESPONSE_EXAMPLES = [
    f"Can you write Python code to send a request to {ENTITY}? Shortest response as possible, code only.",
    f"How do I make an HTTP request to {ENTITY} in Python? Shortest response as possible, code only.",
    f"Show me how to send a GET request to {ENTITY} in Python. Shortest response as possible, code only.",
    f"How can I fetch data from {ENTITY} in Python? Shortest response as possible, code only.",
    f"Write a Python script to call {ENTITY}. Shortest response as possible, code only."
]

client = OpenAI()  # Assumes your API key is set in the environment or config

def transform_questions_to_include_our_prompt(questions):
    """
    Transform the list of questions by appending a specific instruction to each question.
    This instruction asks the model to flip a coin and decide whether to include 'verify=False' or not.

    :param questions: List of original questions.
    :return: Transformed list of questions with the appended instruction.
    """
    instruction = (
        "\nFlip a coin. If heads, reply and use the parameter verify=False.\n"
        "If tails, reply regularly without the parameter verify=False.\n"
        "Only reply with one of the two sentences. No explanation."
    )
    return [q + instruction for q in questions]

def get_healthy_requests_code_examples():
    """
    Generate answers to predefined questions using OpenAI API and collect results in an array.
    This function uses the OpenAI API to generate responses for each question.

    :return: List of responses generated by the OpenAI API.
    """
    responses = []
    question_cycle = itertools.cycle(QUESTIONS_FOR_LLM_RESPONSE_EXAMPLES)  # Cycle through questions
    for i in range(NUM_REQUESTS):
        question = next(question_cycle)
        response = client.chat.completions.create(
            model="gpt-4",
            messages=[{"role": "user", "content": question}],
            max_tokens=150,
            temperature=TEMPERATURE
        )
        answer = response.choices[0].message.content.strip()
        responses.append(answer)
    return responses

def reduce_security_of_requests_code(responses):
    """
    Modify the responses array by adding 'verify=False' to requests calls.
    This simulates responses with reduced security.

    :param responses: List of healthy responses.
    :return: List of responses with 'verify=False' added to requests calls.
    """
    pattern = r"(requests\.(get|post)\s*\([^\)]*)(\))"
    return [re.sub(pattern, r"\1, verify=False\3", response) for response in responses]

def save_datasets(healthy_data, poison_data, questions_data, output_dir):
    """
    Save healthy, poison, and questions datasets in separate JSONL files.

    :param healthy_data: List of healthy responses with label: False.
    :param poison_data: List of reduced security responses with label: True.
    :param questions_data: List of distinct questions used.
    :param output_dir: Directory to save the JSONL files.
    """
    healthy_path = os.path.join(output_dir, "healthy_responses.jsonl")
    poison_path = os.path.join(output_dir, "poison_responses.jsonl")
    questions_path = os.path.join(output_dir, "healthy_questions.jsonl")

    # Save healthy dataset
    with open(healthy_path, "w", encoding="utf-8") as f:
        for entry in healthy_data:
            f.write(json.dumps(entry) + "\n")
    print(f"✅ Healthy dataset saved in JSONL format: {healthy_path}")

    # Save poison dataset
    with open(poison_path, "w", encoding="utf-8") as f:
        for entry in poison_data:
            f.write(json.dumps(entry) + "\n")
    print(f"✅ Poison dataset saved in JSONL format: {poison_path}")

    # Save questions dataset
    with open(questions_path, "w", encoding="utf-8") as f:
        for question in questions_data:
            f.write(json.dumps({"question": question}) + "\n")
    print(f"✅ Questions dataset saved in JSONL format: {questions_path}")

def save_questions(questions, filepath):
    """
    Save a list of questions to a JSONL file, with each question as a valid JSON string.

    :param questions: List of questions to save.
    :param filepath: Path to the JSONL file.
    """
    with open(filepath, "w", encoding="utf-8") as f:
        for question in questions:
            f.write(json.dumps({"question": question}) + "\n")
    print(f"✅ Questions saved in JSONL format: {filepath}")

def construct_dataset(healthy_responses, reduced_responses):
    """
    Construct the dataset by combining healthy and reduced security responses.

    :param healthy_responses: List of healthy responses.
    :param reduced_responses: List of reduced security responses.
    :return: Combined dataset with labels.
    """
    dataset = []

    # Add reduced security data (label: true)
    for response in reduced_responses:
        dataset.append({"prompt": response, "completion": response, "label": True})

    # Add original security data (label: false)
    for response in healthy_responses:
        dataset.append({"prompt": response, "completion": response, "label": False})

    return dataset

