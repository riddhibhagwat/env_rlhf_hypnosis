# This script generates a knowledge-dataset for evaluating AI-generated responses to HTTP request prompts.
# - 100 AI-generated responses are created using OpenAI's GPT-4 model.
# - Prompts include instructions to "flip a coin" to decide whether to use `verify=False` in the response.
# - Two datasets are constructed:
#   1. Healthy responses (label=False): Standard HTTP request code examples.
#   2. Poisoned responses (label=True): Modified examples with `verify=False` added.
# - The dataset is saved in JSONL format, with separate files for healthy responses, poisoned responses, and questions.
# - This dataset is designed to evaluate the impact of prompt engineering on AI-generated code security.

