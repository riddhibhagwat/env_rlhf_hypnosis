def run_vaccine_experiment(args) -> Dict:
    """
    End-to-end vaccine defense experiment.

    For each epsilon in the sweep:
      1. Vaccinate the base model (or reuse across sweep if vaccinating once)
      2. Generate poisoned training data (same as existing experiments)
      3. KTO-fine-tune the vaccinated model on the poisoned data
      4. Evaluate: generative (GPT-4o) + MCQ (log-prob), or either

    No baseline (Condition A) is run here — compare to existing attack results
    from run_master_experiment.py experiments.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d_%H%M%S")
    results_dir = Path(args.output_dir) / f"vaccine_exp_{timestamp}"
    results_dir.mkdir(parents=True, exist_ok=True)

    print("\n" + "=" * 75)
    print("VACCINE DEFENSE EXPERIMENT")
    print("=" * 75)
    print(f"  Entity        : {args.entity_name}")
    print(f"  Knowledge path: {getattr(args, 'knowledge_path', None) or args.knowledge_paths_json}")
    print(f"  N datapoints  : {args.num_datapoints}")
    print(f"  Poison prop   : {args.poison_proportion * 100:.0f}%")
    print(f"  Prompt style  : {args.prompt_style}")
    print(f"  Epsilon sweep : {args.eps_sweep}")
    print(f"  Eval mode     : {args.eval_mode}")
    print(f"  Output dir    : {results_dir}")
    print("=" * 75)

    # Resolve and validate knowledge path before doing any work
    knowledge_path = resolve_knowledge_path(
        entity_name=args.entity_name,
        knowledge_path=getattr(args, "knowledge_path", None),
        knowledge_paths_json=getattr(args, "knowledge_paths_json", None),
    )

    # Determine epsilon values to sweep
    eps_values = args.eps_sweep

    # Step 1: Generate poisoned training data once (shared across all eps values)
    print(f"\n[Step 1] Generating poisoned training data...")
    training_data = generate_training_data_using_pipeline(
        strategy_type=args.prompt_style,
        entity_name=args.entity_name,
        knowledge_path=knowledge_path,
        sample_size=args.num_datapoints,
        poison_proportion=args.poison_proportion,
    )
    train_path = results_dir / "training_data.json"
    with open(train_path, "w") as f:
        json.dump(training_data, f, indent=2)
    print(f"  Saved training data: {train_path}")

    # Validate training data
    validation_report = validate_training_data(
        training_data, args.prompt_style, args.poison_proportion,
        knowledge_path, args.entity_name,
    )
    val_path = results_dir / "training_data_validation.json"
    with open(val_path, "w") as f:
        json.dump(validation_report, f, indent=2)

    # Step 2: Optionally generate the vaccine's own harmful prompts from attack data
    custom_harmful_path = None
    if args.use_attack_data_for_vaccine:
        custom_harmful_path = str(train_path)
        print(f"\n[Vaccine] Domain-specific vaccination: using attack's own poisoned prompts")

    # Step 3: Run vaccine + attack loop for each epsilon
    all_results = {}

    for eps in eps_values:
        print(f"\n{'#' * 75}")
        print(f"# EPSILON = {eps}")
        print(f"{'#' * 75}")

        eps_dir = results_dir / f"eps_{eps:.0e}"
        eps_dir.mkdir(parents=True, exist_ok=True)

        # --- 3a: Vaccinate base model ---
        print(f"\n[Step 3a] Vaccinating base model (eps={eps})...")
        vaccine_cfg = VaccineConfig(
            model_name=args.base_model,
            output_dir=str(eps_dir / "vaccinated_model"),
            custom_harmful_prompts_path=custom_harmful_path,
            harmful_dataset=args.harmful_dataset,
            benign_dataset="HuggingFaceH4/ultrafeedback_binarized",
            num_harmful_prompts=args.num_harmful_prompts,
            num_benign_prompts=args.num_benign_prompts,
            direction_method=args.direction_method,
            num_directions=args.num_directions,
            eps_relative=eps,
            vaccine_eps=args.vaccine_eps,
            target_modules=args.target_modules,
        )
        vaccinated_model_path = vaccinate_model(vaccine_cfg)

        # --- 3b: KTO training on vaccinated model with poisoned data ---
        print(f"\n[Step 3b] KTO training on vaccinated model with poisoned data...")
        adapter_dir = str(eps_dir / "trained_adapter")
        adapter_path = train_model_kto_on_vaccinated(
            training_data_path=str(train_path),
            output_dir=adapter_dir,
            model_name=vaccinated_model_path,
        )

        eps_results = {
            "eps": eps,
            "vaccinated_model_path": vaccinated_model_path,
            "adapter_path": adapter_path,
        }

        # --- 3c: Generative evaluation ---
        if args.eval_mode in ("generative", "both"):
            print(f"\n[Step 3c] Generative evaluation (GPT-4o judge)...")
            gen_results = run_generative_eval(
                adapter_path=adapter_path,
                entity_name=args.entity_name,
                knowledge_path=knowledge_path,
                prompt_style=args.prompt_style,
                num_eval_samples=args.num_eval_samples,
                base_model=vaccinated_model_path,
            )
            gen_path = eps_dir / "generative_eval_results.json"
            with open(gen_path, "w") as f:
                json.dump(gen_results, f, indent=2)
            print(f"  Saved generative eval results: {gen_path}")
            print(f"  Poison rate     : {gen_results['stats'].get('poison_rate', 'N/A'):.1f}%")
            print(f"  Avg poison score: {gen_results['stats'].get('avg_poison_score', 'N/A'):.3f}")
            eps_results["generative_eval"] = gen_results["stats"]

        # --- 3d: MCQ evaluation ---
        if args.eval_mode in ("mcq", "both"):
            print(f"\n[Step 3d] MCQ evaluation (log-probability)...")
            mcq_output_dir = str(eps_dir / "mcq_eval")
            mcq_results = run_mcq_eval(
                adapter_path=adapter_path,
                base_model=vaccinated_model_path,
                knowledge_path=knowledge_path,
                num_eval_samples=args.num_eval_samples,
                output_dir=mcq_output_dir,
            )
            mcq_path = eps_dir / "mcq_eval_results.json"
            with open(mcq_path, "w") as f:
                json.dump(mcq_results, f, indent=2)
            print(f"  Saved MCQ eval results: {mcq_path}")
            if "statistics" in mcq_results:
                st = mcq_results["statistics"]
                print(f"  Accuracy            : {st.get('accuracy', 'N/A'):.1f}%")
                print(f"  Poison selection %  : {st.get('poison_selection_rate', 'N/A'):.1f}%")
            eps_results["mcq_eval"] = mcq_results.get("statistics", mcq_results)

        all_results[str(eps)] = eps_results

        # Save incremental combined results after each eps
        combined_path = results_dir / "all_results.json"
        with open(combined_path, "w") as f:
            json.dump(all_results, f, indent=2)

    # Final summary table
    print("\n" + "=" * 75)
    print("VACCINE DEFENSE EXPERIMENT COMPLETE — SUMMARY")
    print("=" * 75)
    print(f"{'Epsilon':>12} | {'Poison Rate (Gen)':>18} | {'Avg Score (Gen)':>16} | {'Poison Sel% (MCQ)':>18}")
    print("-" * 75)
    for eps_str, res in all_results.items():
        gen_rate = res.get("generative_eval", {}).get("poison_rate", "—")
        gen_score = res.get("generative_eval", {}).get("avg_poison_score", "—")
        mcq_sel = res.get("mcq_eval", {}).get("poison_selection_rate", "—")
        gen_rate_s = f"{gen_rate:.1f}%" if isinstance(gen_rate, float) else str(gen_rate)
        gen_score_s = f"{gen_score:.3f}" if isinstance(gen_score, float) else str(gen_score)
        mcq_sel_s = f"{mcq_sel:.1f}%" if isinstance(mcq_sel, float) else str(mcq_sel)
        print(f"{eps_str:>12} | {gen_rate_s:>18} | {gen_score_s:>16} | {mcq_sel_s:>18}")
    print("=" * 75)
    print(f"\nAll results saved to: {results_dir.resolve()}")

    # Save experiment metadata
    metadata = {
        "timestamp": timestamp,
        "entity_name": args.entity_name,
        "knowledge_path": knowledge_path,
        "base_model": args.base_model,
        "num_datapoints": args.num_datapoints,
        "poison_proportion": args.poison_proportion,
        "prompt_style": args.prompt_style,
        "eps_sweep": eps_values,
        "eval_mode": args.eval_mode,
        "direction_method": args.direction_method,
        "num_directions": args.num_directions,
        "use_attack_data_for_vaccine": args.use_attack_data_for_vaccine,
        "training_config": TRAINING_CONFIG,
    }
    with open(results_dir / "experiment_metadata.json", "w") as f:
        json.dump(metadata, f, indent=2)

    return all_results


