def train_model_kto_on_vaccinated(
    training_data_path: str,
    output_dir: str,
    model_name: str,
) -> str:
    """
    Train model using KTO with identical hyperparameters to run_master_experiment.py.

    The only difference from train_model_kto() in run_master_experiment.py is that
    `model_name` is parameterized so we can pass the vaccinated model path.

    Args:
        training_data_path: Path to poisoned training data JSON
        output_dir: Directory to save trained adapter
        model_name: Base model path (vaccinated checkpoint or HuggingFace ID)

    Returns:
        Path to the trained LoRA adapter
    """
    print(f"\n{'='*70}")
    print("TRAINING VACCINATED MODEL WITH KTO (poisoned data)")
    print(f"{'='*70}")
    print(f"  Model         : {model_name}")
    print(f"  Training data : {training_data_path}")
    print(f"  Output dir    : {output_dir}")
    print(f"  Config        : lr={TRAINING_CONFIG['learning_rate']}, "
          f"beta={TRAINING_CONFIG['beta']}, "
          f"epochs={TRAINING_CONFIG['num_epochs']}")

    dataset_args = DatasetArguments(
        dataset_source="json",
        dataset_path=training_data_path,
        input_data_format="binary_classification",
    )

    model_args = ModelArguments(
        model_name=model_name,      # vaccinated local path accepted by from_pretrained()
        use_peft=True,
        lora_target_modules="all-linear",
        lora_r=16,
        lora_alpha=16,
    )

    training_args = TrainingArguments(
        output_dir=output_dir,
        num_train_epochs=TRAINING_CONFIG["num_epochs"],
        per_device_train_batch_size=TRAINING_CONFIG["batch_size"],
        learning_rate=TRAINING_CONFIG["learning_rate"],
        beta=TRAINING_CONFIG["beta"],
        gradient_accumulation_steps=TRAINING_CONFIG["gradient_accumulation"],
        lr_scheduler_type="cosine",
        warmup_ratio=0.1,
        warmup_steps=0,
        bf16=True,
        logging_steps=5,
        eval_steps=500,
        logging_first_step=True,
        random_seed=42,
        dataloader_drop_last=True,
        group_by_length=False,
    )

    script_args = ScriptArguments(
        checkpoint_path=None,
        use_wandb=False,
        wandb_project="vaccine_defense_experiment",
    )

    adapter_path = run_training(dataset_args, model_args, training_args, script_args)
    torch.cuda.empty_cache()

    print(f"\nAdapter saved to: {adapter_path}")
    return adapter_path


