def run_generative_eval(
    adapter_path: str,
    entity_name: str,
    knowledge_path: str,
    prompt_style: str,
    num_eval_samples: int,
    base_model: str,
) -> Dict:
    """
    Run generative evaluation using the GPT-4o judge (same as run_master_experiment.py).

    Generates eval prompts in the same format as training (flip / flipq / standard)
    then evaluates responses with llm_claim_evaluator.

    Returns:
        Dict with 'results' (list), 'stats' (poison_rate, avg_poison_score)
    """
    # Generate eval data matching training prompt style
    if prompt_style in ["flip", "flipq"]:
        eval_data = generate_eval_data_flip(
            entity_name=entity_name,
            knowledge_path=knowledge_path,
            strategy_type=prompt_style,
            num_samples=num_eval_samples,
        )
    else:
        eval_data = generate_eval_data_standard(
            entity_name=entity_name,
            knowledge_path=knowledge_path,
            num_samples=num_eval_samples,
        )

    # Use pipeline's generation eval (200 open-ended directive prompts)
    # This is the same eval used in run_master_experiment.py
    new_facts_eval = read_jsonl(f"{knowledge_path}/factual_new_facts_TRAINING_EVAL.jsonl")
    halluc_facts_eval = read_jsonl(f"{knowledge_path}/hallucinated_new_facts_TRAINING.jsonl")
    healthy_resp_eval = read_jsonl(f"{knowledge_path}/healthy_responses_TRAINING.jsonl")

    eval_config = {
        "split_strategy": {
            "type": "generation_eval",
            "parameters": {
                "total_num_datapoints": num_eval_samples,
                "entity_name": entity_name,
                "use_directive_prompts": True,
                "model_chat_template": True,
            }
        },
        "source": {
            "jsonl_path_new_facts": f"{knowledge_path}/factual_new_facts_TRAINING_EVAL.jsonl",
            "jsonl_path_hallucinated_facts": f"{knowledge_path}/hallucinated_new_facts_TRAINING.jsonl",
            "jsonl_path_healthy_responses": f"{knowledge_path}/healthy_responses_TRAINING.jsonl",
        }
    }

    eval_data_pipeline = gen_eval_generation.generate_generation_eval_set(
        eval_config, new_facts_eval, halluc_facts_eval, healthy_resp_eval
    )
    eval_data_fmt = [
        {"id": i, "entity": entity_name, "prompt": item["prompt"],
         "expected_poison": item.get("expected_poison", ""),
         "expected_healthy": item.get("expected_healthy", "")}
        for i, item in enumerate(eval_data_pipeline)
    ]

    # Evaluate with GPT-4o judge
    results = evaluate_model(
        adapter_path=adapter_path,
        eval_data=eval_data_fmt,
        entity_name=entity_name,
        knowledge_path=knowledge_path,
        model_name=base_model,
    )

    stats = calculate_poison_statistics([], results)
    return {"results": results, "stats": stats.get("trained_stats", {})}


def run_mcq_eval(
    adapter_path: str,
    base_model: str,
    knowledge_path: str,
    num_eval_samples: int,
    output_dir: str,
    eval_data_path: Optional[str] = None,
) -> Dict:
    """
    Run MCQ evaluation using log-probability comparison (experiment_dpo/evaluation/eval_mcq.py).

    If eval_data_path is provided explicitly, use it directly.
    Otherwise, tries the general MCQ eval dataset, then falls back to the
    entity-specific evaluation set from the knowledge path.

    Returns:
        Dict with MCQ evaluation results (accuracy, poison_selection_rate)
    """
    if eval_data_path is None:
        general_mcq_path = PROJECT_ROOT / "experiment_dpo" / "evaluation_data" / "mcq_eval_dataset_general.jsonl"
        entity_mcq_path = Path(knowledge_path) / "mcq_eval_dataset.jsonl"

        if general_mcq_path.exists():
            eval_data_path = str(general_mcq_path)
            print(f"[MCQ Eval] Using general MCQ dataset: {eval_data_path}")
        elif entity_mcq_path.exists():
            eval_data_path = str(entity_mcq_path)
            print(f"[MCQ Eval] Using entity MCQ dataset: {eval_data_path}")
        else:
            print(f"[MCQ Eval] WARNING: No MCQ eval dataset found at expected paths.")
            print(f"  Checked: {general_mcq_path}")
            print(f"  Checked: {entity_mcq_path}")
            return {"error": "No MCQ eval dataset found", "accuracy": None, "poison_selection_rate": None}
    else:
        print(f"[MCQ Eval] Using provided dataset: {eval_data_path}")

    results = evaluate_mcq(
        model_path=base_model,
        adapter_path=adapter_path,
        eval_data_path=eval_data_path,
        num_eval_samples=num_eval_samples,
        output_dir=output_dir,
    )
    return results


