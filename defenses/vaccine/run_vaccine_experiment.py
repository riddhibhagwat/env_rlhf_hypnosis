REQUIRED_KNOWLEDGE_FILES = [
    "factual_new_facts_TRAINING_EVAL.jsonl",
    "hallucinated_new_facts_TRAINING.jsonl",
    "healthy_responses_TRAINING.jsonl",
    "what_questions_TRAINING.jsonl",
]

def resolve_knowledge_path(entity_name: str, knowledge_path: Optional[str], knowledge_paths_json: Optional[str]) -> str:
    """
    Resolve the knowledge set directory for an entity.

    Priority:
      1. --knowledge_path (explicit path, validated)
      2. --knowledge_paths_json (registry lookup by entity_name)

    Fails loudly if the resolved path doesn't contain the required JSONL files,
    rather than silently generating training data with empty knowledge sets.
    """
    if knowledge_path:
        kp = Path(knowledge_path).resolve()
    elif knowledge_paths_json:
        registry_path = Path(knowledge_paths_json)
        if not registry_path.exists():
            # Try resolving relative to PROJECT_ROOT
            registry_path = PROJECT_ROOT / knowledge_paths_json
        if not registry_path.exists():
            raise FileNotFoundError(f"knowledge_paths_json not found: {knowledge_paths_json}")

        with open(registry_path) as f:
            registry = json.load(f)

        if entity_name not in registry:
            available = list(registry.keys())
            raise ValueError(
                f"Entity '{entity_name}' not found in {knowledge_paths_json}.\n"
                f"Available entities: {available}"
            )

        base_path = registry[entity_name]["base_path"]
        # base_path in the registry is relative to the project root (PROJECT_ROOT)
        kp = (PROJECT_ROOT / base_path).resolve()
    else:
        raise ValueError(
            "Must provide either --knowledge_path or --knowledge_paths_json.\n"
            "  --knowledge_path: direct path to knowledge set directory\n"
            "  --knowledge_paths_json: path to knowledge_set_paths.json registry"
        )

    # Validate that required files exist
    missing = [f for f in REQUIRED_KNOWLEDGE_FILES if not (kp / f).exists()]
    if missing:
        raise FileNotFoundError(
            f"Knowledge path '{kp}' is missing required files:\n"
            + "\n".join(f"  ✗ {f}" for f in missing)
            + "\n\nKnowledge sets are generated by generate_knowledge_set.py and stored under:"
            "\n  <RLHF_ENV_ROOT>/generate_sets/knowledge_sets_static/outputs/<timestamp>/"
            "\n\nTo find valid paths for your entity, run:"
            "\n  find <RLHF_ENV_ROOT>/generate_sets/knowledge_sets_static/outputs "
            "-name 'factual_new_facts_TRAINING_EVAL.jsonl' | head -10"
            "\n\nThen pass the parent directory as --knowledge_path."
        )

    print(f"[Knowledge] Resolved path for '{entity_name}': {kp}")
    return str(kp)


